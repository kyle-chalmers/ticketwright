def shipped(path: Path) -> bool:
    """Whether the file's bytes match a version Ticketwright shipped under bin/."""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest() in SHIPPED_BIN_SHA256
    except OSError:
        return False


def clear_old_bin(bin_dir: Path) -> tuple[list[str], list[str]]:
    """Remove the kit files an older init left in bin_dir; return (removed, kept) file names.

    Only plain files whose bytes match a shipped version go. `kept` names a file that carries a kit
    script's name but differs from every shipped version: it may be the team's, so it stays.
    bin/KIT_VERSION, the older init's mark, is removed only once nothing it marked is left.
    """
    removed, kept = [], []
    if not (bin_dir / "KIT_VERSION").is_file():
        return removed, kept
    kit_names = {p.name for p in Path(__file__).resolve().parent.iterdir() if p.is_file()}
    for f in sorted(bin_dir.iterdir()):
        if f.name in LAUNCHER or f.name == "KIT_VERSION" or f.is_symlink() or not f.is_file():
            continue
        if shipped(f):
            f.unlink()
            removed.append(f.name)
        elif f.name in kit_names:
            kept.append(f.name)
    if not kept:
        (bin_dir / "KIT_VERSION").unlink()
        removed.append("KIT_VERSION")
    return removed, kept
